/** 对齐 PC waitEntryCreateFormFieldSets（add-entry/field/search mock） */
function field(
  infoFieldId,
  setCode,
  setName,
  groupCode,
  groupName,
  columnName,
  fieldName,
  fieldType,
  {
    required = false,
    entryDisplay = true,
    entryImportDisplay = entryDisplay,
    entryImportRequired = required,
    approveDisplay = false,
    approveRequired = false,
    isEntryformRequired = false,
    /** 是否系统字段：1 是 / 0 否；保存时 0 进 customFields */
    systemFlag = 1,
    ...extra
  } = {},
) {
  return {
    id: null,
    infoFieldId,
    setCode,
    setName,
    groupCode,
    groupName,
    columnName,
    fieldName,
    fieldType,
    systemFlag,
    isEntryConfig: true,
    isEntryformRequired,
    required,
    entryDisplay,
    entryImportDisplay,
    entryImportRequired,
    approveDisplay,
    approveRequired,
    ...extra,
  };
}

